const {createContactService}=require('../domains/contacts/contact-service');
const {createCatalogService}=require('../domains/catalog/catalog-service');
const {createInventoryService}=require('../domains/inventory/inventory-service');
const {createInventoryLogisticsService}=require('../domains/inventory/inventory-logistics-service');
const {createInventoryOperationsService}=require('../domains/inventory/inventory-operations-service');
const {createInventoryDepthService}=require('../domains/inventory/inventory-depth-service');
const {createInventoryReservationService}=require('../domains/inventory/inventory-reservation-service');
const {createPagedQueryService}=require('../domains/shared/paged-query-service');
const {extendSalesAdminCompanyOwnership,extendProcurementCompanyOwnership}=require('../domains/shared/company-source-ownership');
const {createFinanceDimensionsService}=require('../domains/finance/finance-dimensions');
const {createFinanceService}=require('../domains/finance/finance-service');
const {createSupplierCreditService}=require('../domains/finance/supplier-credit-service');
const {createStatementImport}=require('../domains/finance/statement-import');
const {createReconciliation}=require('../domains/finance/reconciliation');
const {createRecurrenceService}=require('../domains/finance/recurrence');
const {createFinanceAlertService}=require('../domains/finance/finance-alerts');
const {createProcurementService}=require('../domains/procurement/procurement-service');
const {createRequisitionService}=require('../domains/procurement/requisition-service');
const {createQuotationService}=require('../domains/procurement/quotation-service');
const {createPricingHistoryService}=require('../domains/procurement/pricing-history-service');
const {createSupplierScoringService}=require('../domains/procurement/supplier-scoring-service');
const {createApprovalService}=require('../domains/procurement/approval-service');
const {createAwardService}=require('../domains/procurement/award-service');
const {createReturnService}=require('../domains/procurement/return-service');
const {createSalesAdminService}=require('../domains/sales-admin/sales-admin-service');
