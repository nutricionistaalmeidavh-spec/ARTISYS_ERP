const {createFiscalInteroperabilityService}=require('../domains/tax/fiscal-interoperability-service');
const {extendFiscalProcurementInteroperability}=require('../domains/tax/fiscal-procurement-interoperability');
const {createReportingService}=require('../domains/reports/reporting-service');
const {createBusinessIntelligenceService}=require('../domains/reports/business-intelligence-service');
const {createFinanceDocumentService}=require('../domains/reports/finance-document-service');
const {createFinanceManagementService}=require('../domains/finance/finance-management');

function createErpRuntime({dbPath=':memory:',now=()=>new Date().toISOString(),idFactory,fiscalRuntimeConfig=null}={}){
 const persistent=dbPath!==':memory:';
 const resolvedDbPath=persistent?path.resolve(dbPath):dbPath;
 if(persistent)fs.mkdirSync(path.dirname(resolvedDbPath),{recursive:true});
 const db=openDatabase(resolvedDbPath);
 runErpMigrations(db,now);
 const events=createErpEvents({db,now});
 const common={db,now};
 if(idFactory)common.idFactory=idFactory;
 const auth=createAuthService(common);
 const settings=createSettingsService({db,now});
 const companies=createCompanyService(common);
 const documents=persistent?createDocumentService({...common,storageDir:path.join(path.dirname(resolvedDbPath),'documents')}):null;
 const integrations=createIntegrationService(common);
 const contacts=createContactService(common);
 const catalog=createCatalogService(common);
 const inventory=createInventoryService({...common,catalog});
 const inventoryLogistics=createInventoryLogisticsService({...common,catalog,inventory});
 const inventoryOperations=createInventoryOperationsService({...common,inventory,catalog,events});
 const inventoryDepth=createInventoryDepthService({...common,inventory,catalog});
 const inventoryReservations=createInventoryReservationService({...common,inventory,catalog});
 const financeDimensions=createFinanceDimensionsService(common);
 const finance=createFinanceService({...common,dimensions:financeDimensions});
 const pagedQueries=createPagedQueryService({db,contacts,catalog,finance});
 const supplierCredits=createSupplierCreditService({...common,finance,events});
 const procurementBase=createProcurementService({...common,contacts,catalog,inventory,finance,settings,events});
 const procurement=extendProcurementCompanyOwnership({db,procurement:procurementBase});
 const procurementRequisitions=createRequisitionService({...common,catalog,inventory,events});
 const procurementQuotations=createQuotationService({...common,contacts,catalog,requisitions:procurementRequisitions,events});
 const procurementPricing=createPricingHistoryService({db});
 const procurementScoring=createSupplierScoringService({requisitions:procurementRequisitions,quotations:procurementQuotations,settings,now});
 const procurementApprovals=createApprovalService({...common,settings,events});
 const procurementAwards=createAwardService({...common,scoring:procurementScoring,requisitions:procurementRequisitions,procurement,approvals:procurementApprovals,events});
 const procurementReturns=createReturnService({...common,inventory,finance,supplierCredits,events});
 const salesAdminBase=createSalesAdminService({...common,contacts,catalog,inventory,inventoryLogistics,finance,events});
 const salesAdmin=extendSalesAdminCompanyOwnership({db,salesAdmin:salesAdminBase});
 const retailBase=createRetailOperationsService({...common,catalog,contacts,inventory,finance,salesAdmin});
 const retail=extendRetailWithServiceProducts({...common,catalog,retail:retailBase});
 const serviceOrders=createServiceOrderService({...common,contacts,catalog,inventory,inventoryReservations,finance});
 const manufacturing=createManufacturingService({...common,catalog,inventory,inventoryReservations,retail});
 const mrp=createMrpService({...common,inventory,inventoryReservations,procurementRequisitions,manufacturing});
 const fiscal=createFiscalService({...common,catalog,retail,salesAdmin});
 const fiscalInteroperabilityBase=createFiscalInteroperabilityService({...common,fiscal,retail,salesAdmin,serviceOrders,catalog,contacts});
 const fiscalInteroperability=extendFiscalProcurementInteroperability({...common,fiscal,catalog,contacts,base:fiscalInteroperabilityBase});
 const fiscalRuntime=createFiscalRuntimeService({...common,fiscal,catalog,contacts,retail,salesAdmin,...(fiscalRuntimeConfig||{})});
 const reports=createReportingService({db,now});
 const operations=createOperationsSuite(common);
 const businessIntelligence=createBusinessIntelligenceService({db,reports,inventoryDepth,mrp,now});
 const financeDocuments=createFinanceDocumentService({db,finance,now});
 const financeManagement=createFinanceManagementService({db,finance,reports,now});
 const bankStatements=createStatementImport({...common,finance});
 const financeReconciliation=createReconciliation({...common,finance,statements:bankStatements});
 const financeRecurrences=createRecurrenceService({...common,finance});
 const financeAlerts=createFinanceAlertService({db,finance,financeManagement,settings,now});
 const logger=createSystemLogger({filePath:persistent?path.join(path.dirname(resolvedDbPath),'logs','erp.log'):null,now});
 const health=createSystemHealth({db,dbPath:resolvedDbPath,now});
 const diagnostics=createDiagnosticPackage({health,logger,now});
 const backup=persistent?createBackupService({db,dbPath:resolvedDbPath,backupDir:path.join(path.dirname(resolvedDbPath),'backups'),now}):null;
 logger.info('runtime.started',{persistent});
 let closed=false;
 return{db,events,auth,settings,companies,documents,integrations,contacts,catalog,pagedQueries,inventory,inventoryLogistics,inventoryOperations,inventoryDepth,inventoryReservations,financeDimensions,finance,supplierCredits,procurement,procurementRequisitions,procurementQuotations,procurementPricing,procurementScoring,procurementApprovals,procurementAwards,procurementReturns,salesAdmin,retail,serviceOrders,manufacturing,mrp,fiscal,fiscalInteroperability,fiscalRuntime,reports,operations,businessIntelligence,financeDocuments,financeManagement,bankStatements,financeReconciliation,financeRecurrences,financeAlerts,backup,logger,health,diagnostics,close(){if(closed)return;closed=true;logger.info('runtime.stopping');db.close();}};
}
module.exports={createErpRuntime};
